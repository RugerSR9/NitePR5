static void pack7(uint8_t rows[8], const uint8_t g[7])
{
    int y;
    memset(rows, 0, 8);
    for (y = 0; y < 7; y++) {
        rows[y + 1] = (uint8_t)(g[y] << 1);
    }
}

void font_glyph(unsigned char c, uint8_t rows[8])
{
    memset(rows, 0, 8);
    if (c >= 'a' && c <= 'z') {
        c = (unsigned char)(c - 32);
    }
    if (c >= '0' && c <= '9') {
        pack7(rows, k_digit[c - '0']);
        return;
    }
    if (c >= 'A' && c <= 'Z') {
        pack7(rows, k_alpha[c - 'A']);
        return;
    }
    switch (c) {
    case ' ':
        break;
    case ':':
        rows[2] = 0x10;
        rows[5] = 0x10;
        break;
    case '.':
        rows[6] = 0x10;
        break;
    case '/':
        rows[1] = 0x02;
        rows[2] = 0x04;
        rows[3] = 0x08;
        rows[4] = 0x10;
        rows[5] = 0x20;
        break;
    case '-':
        rows[4] = 0x1E;
        break;
    case '+':
        rows[2] = 0x08;
        rows[3] = 0x08;
        rows[4] = 0x3E;
        rows[5] = 0x08;
        rows[6] = 0x08;
        break;
    case '=':
        rows[3] = 0x1E;
        rows[5] = 0x1E;
        break;
    case '?':
        rows[1] = 0x0E;
        rows[2] = 0x11;
        rows[3] = 0x02;
        rows[4] = 0x04;
        rows[6] = 0x04;
        break;
    case '!':
        rows[1] = 0x08;
        rows[2] = 0x08;
        rows[3] = 0x08;
        rows[4] = 0x08;
        rows[6] = 0x08;
        break;
    case '[':
        rows[1] = 0x1C;
        rows[2] = 0x10;
        rows[3] = 0x10;
        rows[4] = 0x10;
        rows[5] = 0x10;
        rows[6] = 0x1C;
        break;
    case ']':
        rows[1] = 0x1C;
        rows[2] = 0x04;
        rows[3] = 0x04;
        rows[4] = 0x04;
        rows[5] = 0x04;
        rows[6] = 0x1C;
        break;
    case '|':
        rows[1] = 0x08;
        rows[2] = 0x08;
        rows[3] = 0x08;
        rows[4] = 0x08;
        rows[5] = 0x08;
        rows[6] = 0x08;
        break;
    case '_':
        rows[7] = 0x3E;
        break;
    case '*':
        rows[2] = 0x15;
        rows[3] = 0x0E;
        rows[4] = 0x1F;
        rows[5] = 0x0E;
        rows[6] = 0x15;
        break;
    case '#':
        rows[2] = 0x0A;
        rows[3] = 0x1F;
        rows[4] = 0x0A;
        rows[5] = 0x1F;
        rows[6] = 0x0A;
        break;
    case '%':
        rows[1] = 0x11;
        rows[2] = 0x02;
        rows[3] = 0x04;
        rows[4] = 0x08;
        rows[5] = 0x10;
        rows[6] = 0x11;
        break;
    case '<':
        rows[2] = 0x04;
        rows[3] = 0x08;
        rows[4] = 0x10;
        rows[5] = 0x08;
        rows[6] = 0x04;
        break;
    case '>':
        rows[2] = 0x10;
        rows[3] = 0x08;
        rows[4] = 0x04;
        rows[5] = 0x08;
        rows[6] = 0x10;
        break;
    case '\'':
        rows[1] = 0x08;
        rows[2] = 0x08;
        break;
    case '(':
        rows[1] = 0x04;
        rows[2] = 0x08;
        rows[3] = 0x10;
        rows[4] = 0x10;
        rows[5] = 0x08;
        rows[6] = 0x04;
        break;
    case ')':
        rows[1] = 0x10;
        rows[2] = 0x08;
        rows[3] = 0x04;
        rows[4] = 0x04;
        rows[5] = 0x08;
        rows[6] = 0x10;
        break;
    case ',':
        rows[6] = 0x08;
        rows[7] = 0x10;
        break;
    case 'x':
    case 'X':
        pack7(rows, k_alpha['X' - 'A']);
        break;
    default:
        rows[1] = 0x1F;
        rows[2] = 0x11;
        rows[3] = 0x11;
        rows[4] = 0x11;
        rows[5] = 0x11;
        rows[6] = 0x1F;
        break;
    }
}
